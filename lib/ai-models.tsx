/** Flat list of all models. */
export const AIModelsType: AIModel[] = AIModelGroups.flatMap((g) => g.models);

export type AIModelsType = typeof AIModelsType;

/** Looks a model up by its `id` — never by display `name`, which repeats
 *  across entries (e.g. "Qwen 3.8 Max · OpenRouter" vs "· Tongyi") and must
 *  never be sent to Dify. */
export function getAIModelById(id: string | null | undefined): AIModel | undefined {
  return id ? AIModelsType.find((m) => m.id === id) : undefined;
}

/** General Chat default — Qwen 3.7 Flash (`qwen3.7-flash`). */
export const DEFAULT_AI_MODEL: AIModel =
  getAIModelById("qwen3.7-flash") ?? AIModelsType[0];

/** Validates a possibly-stale model reference (an id, or a model object held
 *  in state from an earlier catalog) and falls back to DEFAULT_AI_MODEL when
 *  it is no longer offered. */
export function resolveAIModel(
  candidate: AIModel | string | null | undefined,
): AIModel {
  if (!candidate) return DEFAULT_AI_MODEL;
  const id = typeof candidate === "string" ? candidate : candidate.id;
  return getAIModelById(id) ?? DEFAULT_AI_MODEL;
}

/** The single conversion used when building a General Chat request: selected
 *  model → exact Dify `inputs.model_selector` key. Display names (`.name`)
 *  are never sent. */
export function resolveModelSelector(model: AIModel | null | undefined): string {
  return resolveAIModel(model).id;
}
